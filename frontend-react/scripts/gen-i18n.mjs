const outDir = path.resolve(__dirname, "../src/i18n/messages");
fs.mkdirSync(outDir, { recursive: true });

for (const loc of Object.keys(translations)) {
  const extras =
    loc === "en" ? extraEn : loc === "es" ? extraEs : extraEn;
  const merged = { ...extraEn, ...translations[loc], ...extras };
  const content = `const messages = ${JSON.stringify(merged, null, 2)} as const;\n\nexport default messages;\n`;
  fs.writeFileSync(path.join(outDir, `${loc}.ts`), content);
}

fs.copyFileSync(path.join(outDir, "en.ts"), path.join(outDir, "en-gb.ts"));
